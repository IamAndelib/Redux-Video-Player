"""WCAG contrast report on the app's palette (QA layer L7, Q0.4).

  python3 -I redux/qa/contrast.py <dump dir> <report.md>

Reads the palette dumps the app writes when REDUX_PALETTE_DUMP is set (night.tsv, day.tsv: every ColorContext set,
section, name and state; modules/gui/qt/style/palettedump.cpp; run by redux/qa/contrast.sh) and writes a Markdown
report with every foreground/background pair per set, its contrast ratio in each state, and the WCAG 2.x minimum:
- text: 4.5:1 (1.4.3), every Fg colour on Bg.Primary and Bg.Secondary, or a role colour (Highlight, Negative…) on
  its own Bg colour where the set defines one (a selected row);
- focus ring, borders and indicators (Decoration on Bg.Primary): 3:1 (1.4.11, 2.4.11).
Disabled colours are listed but exempt (1.4.3 excludes inactive components); a fully transparent foreground
isn't drawn ("none": the focus ring outside Focused). Translucent colours are composited
first: a foreground on its background, a translucent background on the View background (axe-core's approach, idea
only). Magenta (#ff00ff) is getColor()'s "not defined", so those pairs are left out.

Appends `l7.contrast` to $QA_RESULTS when it's set: fail when an active pair is below its minimum.
"""

import collections
import os
import sys

TEXT, NON_TEXT = 4.5, 3.0
STATES = ["Normal", "Hovered", "Focused", "Pressed", "Disabled"]
UNDEFINED = "#ffff00ff"


def rgba(argb):
    """'#aarrggbb' as (r, g, b, a), each 0..1."""
    v = [int(argb[i:i + 2], 16) / 255 for i in (3, 5, 7, 1)]
    return tuple(v)


def over(top, bottom):
    """`top` composited over an opaque `bottom`."""
    a = top[3]
    return tuple(a * t + (1 - a) * b for t, b in zip(top[:3], bottom[:3])) + (1.0,)


def luminance(c):
    lin = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in c[:3]]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def ratio(fg, bg):
    hi, lo = sorted((luminance(fg), luminance(bg)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def load(path):
    colors = {}
    with open(path) as f:
        next(f)
        for line in f:
            s, section, name, state, color = line.rstrip("\n").split("\t")
            colors[s, section, name, state] = color
    return colors


def scheme_rows(colors):
    """[(set, pair, minimum, {state: ratio}), …] and how many pairs are below their minimum in an active state."""
    sets = list(dict.fromkeys(k[0] for k in colors))
    fg_names = sorted({k[2] for k in colors if k[1] == "Fg"})
    decorations = ["VisualFocus", "Border", "Indicator"]
    view_bg = rgba(colors["View", "Bg", "Primary", "Normal"])
    rows, failing = [], 0
    for s in sets:
        # A role colour (Highlight, Negative…) is drawn on its own background where the set defines one (a selected
        # row: Fg.Highlight on Bg.Highlight); otherwise text goes on the primary and secondary backgrounds.
        own_bg = {n for n in fg_names if n not in ("Primary", "Secondary")
                  and colors.get((s, "Bg", n, "Normal"), UNDEFINED) != UNDEFINED}
        pairs = [(f"Fg.{n}", ("Fg", n), f"Bg.{n}", n, TEXT) for n in sorted(own_bg)]
        pairs += [(f"Fg.{n}", ("Fg", n), f"Bg.{b}", b, TEXT)
                  for b in ("Primary", "Secondary") for n in fg_names if n not in own_bg]
        pairs += [(f"Decoration.{n}", ("Decoration", n), "Bg.Primary", "Primary", NON_TEXT) for n in decorations]
        for fg_label, (section, name), bg_label, bg_name, minimum in pairs:
            ratios = {}
            for state in STATES:
                fg, bg = colors[s, section, name, state], colors[s, "Bg", bg_name, state]
                if UNDEFINED in (fg, bg):
                    continue
                if rgba(fg)[3] == 0:   # not drawn in this state (e.g. the focus ring outside Focused)
                    ratios[state] = None
                    continue
                background = over(rgba(bg), view_bg)
                ratios[state] = ratio(over(rgba(fg), background), background)
            if ratios:
                rows.append((s, f"{fg_label} on {bg_label}", minimum, ratios))
                failing += any(r is not None and r < minimum for state, r in ratios.items() if state != "Disabled")
    return rows, failing


def main():
    dump, report = sys.argv[1], sys.argv[2]
    lines = ["# Contrast report (WCAG 2.x)", "",
             "Every foreground/background pair of every `ColorContext` set, per state. Minimums: text 4.5:1, focus "
             "ring, borders and indicators 3:1; **bold** is below the minimum; disabled is listed but exempt; none: "
             "not drawn in that state (transparent). "
             "Generated by `redux/qa/contrast.sh` (Q0.4).", ""]
    summary, total_failing = [], 0
    for scheme in ("night", "day"):
        path = os.path.join(dump, f"{scheme}.tsv")
        if not os.path.exists(path):
            summary.append(f"{scheme}: no dump")
            total_failing += 1
            continue
        rows, failing = scheme_rows(load(path))
        total_failing += failing
        summary.append(f"{scheme}: {len(rows)} pairs, {failing} below the minimum")
        lines += [f"## {scheme.capitalize()}", "", "| Set | Pair | Min | " + " | ".join(STATES) + " |",
                  "|---|---|---|" + "---|" * len(STATES)]
        for s, pair, minimum, ratios in rows:
            cells = []
            for state in STATES:
                r = ratios.get(state)
                cell = "none" if state in ratios and r is None else "–" if r is None else f"{r:.2f}"
                cells.append(f"**{cell}**" if r is not None and state != "Disabled" and r < minimum else cell)
            lines.append(f"| {s} | {pair} | {minimum:g} | " + " | ".join(cells) + " |")
        lines.append("")
    lines[4:4] = ["**Summary:** " + "; ".join(summary) + ".", ""]
    with open(report, "w") as out:
        out.write("\n".join(lines) + "\n")
    status = "pass" if total_failing == 0 else "fail"
    detail = "; ".join(summary) + f"; see {report}"
    if os.environ.get("QA_RESULTS"):
        with open(os.environ["QA_RESULTS"], "a") as out:
            out.write(f"l7.contrast\t{status}\t{detail}\n")
    print(f"  {status}  l7.contrast  ({detail})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
